<?php

namespace App\Actions\Fortify;

use App\Concerns\PasswordValidationRules;
use App\Concerns\ProfileValidationRules;
use App\Models\User;
use Illuminate\Support\Facades\Validator;
use Illuminate\Validation\ValidationException;
use Laravel\Fortify\Contracts\CreatesNewUsers;

class CreateNewUser implements CreatesNewUsers
{
    use PasswordValidationRules, ProfileValidationRules;

    /**
     * Validate and create a newly registered user.
     *
     * MINITOR is single-admin, self-hosted software: registration only ever
     * creates the one operator account on first launch. Once that account
     * exists, this is the server-side backstop against creating another one
     * (the register route/view are already gated too, in
     * FortifyServiceProvider).
     *
     * @param  array<string, string>  $input
     */
    public function create(array $input): User
    {
        if (User::query()->exists()) {
            throw ValidationException::withMessages([
                'email' => 'This MINITOR instance already has an admin account. Registration is closed.',
            ]);
        }

        Validator::make($input, [
            ...$this->profileRules(),
            'password' => $this->passwordRules(),
        ])->validate();

        return User::create([
            'name' => $input['name'],
            'email' => $input['email'],
            'password' => $input['password'],
        ]);
    }
}
